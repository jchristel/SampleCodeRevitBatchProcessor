using System.Reflection;
using System.Text;

// usage: stubgen <RevitAPI.dll> <outputRoot> <revitVersionLabel>
string dll = args[0], outRoot = args[1], label = args[2];
var coreDir = System.Runtime.InteropServices.RuntimeEnvironment.GetRuntimeDirectory();
var paths = Directory.GetFiles(coreDir, "*.dll").Concat(new[] { dll }).ToList();
using var mlc = new MetadataLoadContext(new PathAssemblyResolver(paths));
var asm = mlc.LoadFromAssemblyPath(dll);

Type[] types;
try { types = asm.GetExportedTypes(); }
catch (ReflectionTypeLoadException e) { types = e.Types.Where(t => t != null).ToArray()!; }

string Clean(string n) { var i = n.IndexOf('`'); return i >= 0 ? n[..i] : n; }
string[] reserved = { "None", "True", "False", "from", "import", "class", "def", "pass", "lambda", "global", "in", "is", "not", "or", "and", "with", "as", "if", "else", "elif", "for", "while", "try", "except", "finally", "raise", "return", "yield", "del", "assert", "break", "continue", "nonlocal", "print", "exec" };
string Id(string n) => reserved.Contains(n) ? n + "_" : n;

var byNs = types.Where(t => !t.IsNested && t.Namespace != null && t.Namespace.StartsWith("Autodesk.Revit")).GroupBy(t => t.Namespace!);
int total = 0;
foreach (var g in byNs)
{
    var dir = Path.Combine(new[] { outRoot }.Concat(g.Key.Split('.')).ToArray());
    Directory.CreateDirectory(dir);
    // package __init__ files for every parent namespace
    var parts = g.Key.Split('.');
    for (int i = 1; i <= parts.Length; i++)
    {
        var pd = Path.Combine(new[] { outRoot }.Concat(parts.Take(i)).ToArray());
        Directory.CreateDirectory(pd);
        var pi = Path.Combine(pd, "__init__.py");
        if (!File.Exists(pi)) File.WriteAllText(pi, "");
    }
    var names = g.Select(t => Clean(t.Name)).ToHashSet();
    var map = g.GroupBy(t => Clean(t.Name)).ToDictionary(x => x.Key, x => x.First());

    // order classes so that a base class is defined before its subclasses
    var ordered = new List<Type>(); var done = new HashSet<string>();
    void Visit(Type t)
    {
        var n = Clean(t.Name);
        if (!done.Add(n)) return;
        Type? b = null; try { b = t.BaseType; } catch { }
        if (b != null && b.Namespace == g.Key && map.TryGetValue(Clean(b.Name), out var bt)) Visit(bt);
        ordered.Add(map[n]);
    }
    foreach (var t in map.Values.OrderBy(t => Clean(t.Name))) Visit(t);

    var sb = new StringBuilder();
    sb.AppendLine($"# Generated by stubgen from the Revit API reference assembly ({label}). Names only: classes, enums, members.");
    sb.AppendLine("# Do not edit. Behaviour needed by tests belongs in the overrides module.");
    foreach (var t in ordered)
    {
        total++;
        var n = Clean(t.Name);
        if (t.IsEnum)
        {
            sb.AppendLine($"class {n}(object):");
            int i = 0; bool any = false;
            foreach (var f in t.GetFields(BindingFlags.Public | BindingFlags.Static))
            {
                long v; try { v = Convert.ToInt64(f.GetRawConstantValue()); } catch { v = i; }
                sb.AppendLine($"    {Id(f.Name)} = {v}"); any = true; i++;
            }
            if (!any) sb.AppendLine("    pass");
            sb.AppendLine();
            continue;
        }
        string baseName = "object";
        try
        {
            var b = t.BaseType;
            if (!t.IsInterface && b != null && b.Namespace == g.Key && names.Contains(Clean(b.Name))) baseName = Clean(b.Name);
        }
        catch { }
        sb.AppendLine($"class {n}({baseName}):");
        var body = new List<string>();
        bool ctor = false;
        BindingFlags bf = BindingFlags.Public | BindingFlags.Instance | BindingFlags.Static | BindingFlags.DeclaredOnly;
        try
        {
            var members = new HashSet<string>();
            foreach (var m in t.GetMethods(bf))
            {
                if (m.IsSpecialName) continue;
                if (!members.Add(m.Name)) continue;
                if (m.IsStatic) { body.Add("    @staticmethod"); body.Add($"    def {Id(m.Name)}(*args, **kwargs):"); }
                else body.Add($"    def {Id(m.Name)}(self, *args, **kwargs):");
                body.Add("        return None");
            }
            foreach (var p in t.GetProperties(bf))
            {
                if (p.GetIndexParameters().Length > 0) continue;
                if (!members.Add(p.Name)) continue;
                body.Add($"    {Id(p.Name)} = None");
            }
            foreach (var f in t.GetFields(bf))
            {
                if (!members.Add(f.Name)) continue;
                body.Add($"    {Id(f.Name)} = None");
            }
        }
        catch { }
        if (!t.IsInterface)
        {
            body.Insert(0, "    def __init__(self, *args, **kwargs):");
            body.Insert(1, "        pass");
        }
        if (body.Count == 0) body.Add("    pass");
        foreach (var l in body) sb.AppendLine(l);
        sb.AppendLine();
    }
    File.WriteAllText(Path.Combine(dir, "__init__.py"), sb.ToString());
}
Console.WriteLine($"{total} types written to {outRoot}");
